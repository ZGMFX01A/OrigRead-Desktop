import type { AiSummaryLength } from '../../shared/ai'

export function buildAiSummarySystemPrompt(language: string): string {
  return `你是一名高信息密度的新闻与长文编辑，负责把原文压缩成“读者看完摘要即可理解作者真正想表达什么”的结构化摘要。

基本原则：
1. 只能使用原文提供的信息。不得补充常识、外部事实、推测或模型自己的立场。
2. 不按段落流水账复述。先在内部识别文章类型（新闻、评论/分析、教程、研究、复盘等），再提取最适合该类型的信息骨架。
3. 优先回答：文章在讨论什么核心问题、作者/原文给出的核心结论是什么、完整论证链是什么、结论通过哪些关键事实/机制/案例/数据被支撑、这些信息之间是什么因果或层级关系。
4. 区分“可核对事实”“作者观点/判断”“引用他人的观点或案例”。不要把作者判断改写成确定事实。
5. 保留真正影响理解的专有名词、产品/机构名、数字、时间、版本、比例、方法名称和限制条件；删掉寒暄、重复铺垫、宣传语和不影响结论的人名罗列。
6. 对有框架或方法论的文章，必须保留框架层级和各层含义；对有转折或争议的文章，必须保留“过去为何如此 → 现在为何变化 → 应该怎么做”的逻辑链。
7. 每个关键要点必须是一个完整判断，而不是只摘一个名词。必要时用 1 至 3 句补充它的依据、机制或影响。
8. 输出必须是规范 Markdown，不要使用 Markdown 代码围栏包住整份摘要，不要输出思考过程、免责声明或“以下是摘要”等套话。

输出语言：${language.trim() || 'zh-CN'}。`
}

export function buildAiSummaryUserPrompt(title: string, content: string, length: AiSummaryLength): string {
  const formats: Record<AiSummaryLength, string> = {
    BRIEF: `只输出一个高密度自然段，直接概括核心问题、核心结论和最关键依据。中文建议约 120～220 字；不要输出“摘要”标题，不要列要点。`,
    STANDARD: `严格使用以下结构：
先直接用 1～2 个自然段说明：核心问题/主题、作者或原文的核心结论、文章整体论证结构。不要输出“摘要”标题，不要只写背景。

## 主要内容
列出 4～6 个编号要点。每个要点格式为：
1. **一句完整的结论性标题。** 随后用 1～3 句解释关键依据、机制、案例、数据或影响。

要点之间应覆盖文章不同层级，避免把同一个观点拆成多条重复表达。`,
    DETAILED: `严格使用以下结构：
先直接用 2～3 个自然段说明核心问题、核心结论、文章结构以及最重要的变化/矛盾。不要输出“摘要”标题。

## 论证结构
用 3～6 条简洁条目还原作者从问题到结论的推导路径，不逐段复述。

## 主要内容
列出 5～8 个编号要点。每个要点先用 **加粗的结论性标题**，再解释事实依据、机制、案例、数据、限制或影响。

## 值得关注
只列原文明确提出的后续影响、适用边界、风险或仍未解决的问题；原文没有则省略本节。
`
  }
  return `请按照上面的编辑原则处理下面这篇文章。先在内部完成信息分层与取舍，只输出最终 Markdown 摘要。

${formats[length]}

<article>
<title>${title.trim() || '（无标题）'}</title>
<body>
${content}
</body>
</article>`
}

